"""Request payloads (TypedDicts) and response models (dataclasses) for the Midwater API.

Response models keep the full decoded JSON in ``raw`` so fields added to the API later are
reachable before the SDK names them.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Any, Dict, List, Literal, Optional, TypedDict

__all__ = [
    "Channel",
    "Speaker",
    "EndedBy",
    "ConversationStatus",
    "Outcome",
    "CheckResultValue",
    "DecidedBy",
    "HealthStatus",
    "Environment",
    "FeedbackValue",
    "Turn",
    "Event",
    "AgentRef",
    "GroupRef",
    "ConversationCreate",
    "FeedbackCreate",
    "ConversationAccepted",
    "ConversationAgent",
    "GroupSummary",
    "CheckResult",
    "Conversation",
    "Feedback",
    "HealthWindow",
    "AgentHealth",
    "GroupHealthAgent",
    "GroupHealth",
    "WebhookEvent",
]

Channel = Literal["voice", "chat"]
Speaker = Literal["agent", "user", "human_agent"]
EndedBy = Literal["agent", "caller", "user", "human_agent", "timeout", "system"]
ConversationStatus = Literal["queued", "evaluating", "done", "failed"]
Outcome = Optional[Literal["resolved", "unresolved", "escalated", "not_real_inquiry"]]
CheckResultValue = Literal["pass", "fail", "uncertain", "not_applicable", "met", "not_met"]
DecidedBy = Optional[Literal["rule", "model", "llm_judge", "human"]]
HealthStatus = Literal["healthy", "watch", "at_risk", "not_enough_calls"]
Environment = Literal["test", "live"]
FeedbackValue = Literal["pass", "fail"]


# --------------------------------------------------------------------------- request payloads


class _TurnRequired(TypedDict):
    speaker: Speaker
    text: str


class Turn(_TurnRequired, total=False):
    """One transcript turn."""

    start_ms: int
    end_ms: int
    asr_confidence: float


class _EventRequired(TypedDict):
    type: str


class Event(_EventRequired, total=False):
    """Something the agent did: a tool call, a transfer, a handoff. The API keeps extra keys."""

    name: str
    status: str
    target: str
    at_ms: int


class AgentRef(TypedDict, total=False):
    """The AI agent that handled the conversation. Omit it to use the project's Default agent."""

    id: str
    name: str
    version: str


class _GroupRefRequired(TypedDict):
    id: str


class GroupRef(_GroupRefRequired, total=False):
    """Files the agent into this group the first time the agent is seen without one."""

    name: str


class _ConversationCreateRequired(TypedDict):
    external_id: str
    channel: Channel
    transcript: List[Turn]


class ConversationCreate(_ConversationCreateRequired, total=False):
    """Body of ``POST /v1/conversations``."""

    started_at: str
    ended_at: str
    ended_by: EndedBy
    agent: AgentRef
    group: GroupRef
    events: List[Event]
    metadata: Dict[str, Any]


class _FeedbackCreateRequired(TypedDict):
    check_key: str
    verdict: FeedbackValue


class FeedbackCreate(_FeedbackCreateRequired, total=False):
    """Body of ``POST /v1/conversations/{id}/feedback``."""

    note: str


# --------------------------------------------------------------------------- response models


def _opt_str(value: Any) -> Optional[str]:
    return None if value is None else str(value)


def _opt_float(value: Any) -> Optional[float]:
    return None if value is None else float(value)


def _opt_int(value: Any) -> Optional[int]:
    return None if value is None else int(value)


@dataclass
class ConversationAccepted:
    """Answer to ``conversations.create()``.

    ``duplicate`` is true when the ``external_id`` already existed (HTTP 200, nothing new was
    created). ``replayed`` is true when the answer is a replay of an earlier request with the
    same ``Idempotency-Key``. ``idempotency_key`` is the key that was sent (generated by the
    SDK when you didn't pass one).
    """

    id: str
    status: ConversationStatus
    duplicate: bool = False
    replayed: bool = False
    idempotency_key: Optional[str] = None
    raw: Dict[str, Any] = field(default_factory=dict, repr=False, compare=False)

    @classmethod
    def from_dict(
        cls,
        data: Mapping[str, Any],
        *,
        replayed: bool = False,
        idempotency_key: Optional[str] = None,
    ) -> ConversationAccepted:
        return cls(
            id=str(data["id"]),
            status=data["status"],
            duplicate=bool(data.get("duplicate", False)),
            replayed=replayed,
            idempotency_key=idempotency_key,
            raw=dict(data),
        )


@dataclass
class ConversationAgent:
    id: str
    name: str
    version: Optional[str] = None

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> ConversationAgent:
        return cls(
            id=str(data["id"]),
            name=str(data.get("name", "")),
            version=_opt_str(data.get("version")),
        )


@dataclass
class GroupSummary:
    id: str
    name: str

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> GroupSummary:
        return cls(id=str(data["id"]), name=str(data.get("name", "")))

    @classmethod
    def from_optional(cls, data: Any) -> Optional[GroupSummary]:
        return cls.from_dict(data) if isinstance(data, Mapping) else None


@dataclass
class CheckResult:
    """The result of one check on one conversation.

    ``verdict`` is the check's result: ``pass`` (no problem found), ``fail`` (Midwater found
    this problem), ``uncertain`` (a person should look), ``not_applicable``, or ``met`` /
    ``not_met`` for gating questions. ``decided_by`` says how it was reached: ``rule`` (from
    the events you sent), ``model`` (Midwater's model read the conversation), ``llm_judge``
    (a second review for unclear conversations) or ``human``.
    """

    check_key: str
    check_version: int
    check_status: str
    verdict: CheckResultValue
    scorer_version: str
    check_name: Optional[str] = None
    score: Optional[float] = None
    choice: Optional[str] = None
    decided_by: DecidedBy = None
    reason: Optional[str] = None
    evidence_turns: List[Any] = field(default_factory=list)
    latency_ms: Optional[int] = None
    raw: Dict[str, Any] = field(default_factory=dict, repr=False, compare=False)

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> CheckResult:
        return cls(
            check_key=str(data["check_key"]),
            check_version=int(data.get("check_version", 0)),
            check_status=str(data.get("check_status", "")),
            verdict=data["verdict"],
            scorer_version=str(data.get("scorer_version", "")),
            check_name=_opt_str(data.get("check_name")),
            score=_opt_float(data.get("score")),
            choice=_opt_str(data.get("choice")),
            decided_by=data.get("decided_by"),
            reason=_opt_str(data.get("reason")),
            evidence_turns=list(data.get("evidence_turns") or []),
            latency_ms=_opt_int(data.get("latency_ms")),
            raw=dict(data),
        )


@dataclass
class Conversation:
    """A conversation, its scoring ``status``, its ``outcome`` and every check result.

    ``results`` fills in once ``status`` is ``done``.
    """

    id: str
    external_id: str
    channel: Channel
    status: ConversationStatus
    outcome: Outcome
    dashboard_url: str
    agent: ConversationAgent
    group: Optional[GroupSummary]
    transcript: List[Turn]
    events: List[Event]
    metadata: Dict[str, Any]
    results: List[CheckResult]
    started_at: Optional[str] = None
    ended_at: Optional[str] = None
    ended_by: Optional[str] = None
    raw: Dict[str, Any] = field(default_factory=dict, repr=False, compare=False)

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> Conversation:
        return cls(
            id=str(data["id"]),
            external_id=str(data.get("external_id", "")),
            channel=data.get("channel", "voice"),
            status=data["status"],
            outcome=data.get("outcome"),
            dashboard_url=str(data.get("dashboard_url", "")),
            agent=ConversationAgent.from_dict(data.get("agent") or {"id": ""}),
            group=GroupSummary.from_optional(data.get("group")),
            transcript=list(data.get("transcript") or []),
            events=list(data.get("events") or []),
            metadata=dict(data.get("metadata") or {}),
            results=[CheckResult.from_dict(r) for r in data.get("results") or []],
            started_at=_opt_str(data.get("started_at")),
            ended_at=_opt_str(data.get("ended_at")),
            ended_by=_opt_str(data.get("ended_by")),
            raw=dict(data),
        )


